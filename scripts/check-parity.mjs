/**
 * Emits a SQL script that replays the shared vectors against the authoritative
 * SQL implementation, and compares the TypeScript transition matrix with the
 * order_transitions table.
 *
 * Pricing is implemented twice on purpose (see docs/ARCHITECTURE.md §6). This
 * is what stops the two copies from drifting apart.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const vectors = JSON.parse(readFileSync(
  fileURLToPath(new URL('packages/domain/src/pricing-vectors.json', root)), 'utf8'));

// Import the TypeScript sources directly: Node 22 strips the types.
const { computeDeliveryFee } = await import(
  new URL('packages/domain/src/pricing.ts', root).href);
const { ALLOWED_TRANSITIONS } = await import(
  new URL('packages/domain/src/order-state.ts', root).href);

const lines = [];
const sqlLit = s => `'${String(s).replace(/'/g, "''")}'`;

lines.push(`
-- GENERATED by scripts/check-parity.mjs — do not edit by hand.
\\set ON_ERROR_STOP on
set client_min_messages = warning;
create schema if not exists test;
drop table if exists test.parity;
create table test.parity (
  id serial primary key, kind text, label text, passed boolean, detail text);
`);

// ---------------------------------------------------------------- settings
for (const [key, value] of Object.entries(vectors.settings)) {
  const settingKey =
    key === 'grouped_round_discount' ? 'pricing.grouped_round_discount'
    : key === 'surge_min' ? 'pricing.surge_min'
    : key === 'surge_max' ? 'pricing.surge_max'
    : `pricing.${key}`;

  lines.push(`
insert into test.parity (kind, label, passed, detail)
select 'settings', ${sqlLit(`le vecteur ${key} correspond à app_settings`)},
       (app.setting(${sqlLit(settingKey)}) #>> '{}')::double precision = ${value},
       format('SQL=%s vecteur=%s', app.setting(${sqlLit(settingKey)}) #>> '{}', ${value});`);
}

// ---------------------------------------------------------------- pricing
for (const c of vectors.cases) {
  const ts = computeDeliveryFee(
    { pallets: c.pallets, floor: c.floor, hasLift: c.hasLift, surge: c.surge, mode: c.mode },
    vectors.settings);

  if (ts !== c.expectedDeliveryCents) {
    console.error(`TypeScript disagrees with its own vector on "${c.name}": ` +
                  `${ts} != ${c.expectedDeliveryCents}`);
    process.exit(1);
  }

  lines.push(`
insert into test.parity (kind, label, passed, detail)
select 'pricing', ${sqlLit(c.name)},
       app.compute_delivery_fee(${c.pallets}, ${c.floor}, ${c.hasLift}, ${c.surge}, ${sqlLit(c.mode)}) = ${ts},
       format('SQL=%s TypeScript=%s',
              app.compute_delivery_fee(${c.pallets}, ${c.floor}, ${c.hasLift}, ${c.surge}, ${sqlLit(c.mode)}), ${ts});`);
}

// ---------------------------------------------------------------- invalid surge
for (const c of vectors.invalidCases) {
  lines.push(`
do $parity$
declare refused boolean := false;
begin
  begin
    perform app.compute_delivery_fee(${c.pallets}, ${c.floor}, ${c.hasLift}, ${c.surge}, ${sqlLit(c.mode)});
  exception when others then refused := true;
  end;
  insert into test.parity (kind, label, passed, detail)
  values ('pricing', ${sqlLit('refus SQL : ' + c.name)}, refused, null);
end;
$parity$;`);
}

// ---------------------------------------------------------------- transitions
const tsPairs = ALLOWED_TRANSITIONS.map(([a, b]) => `(${sqlLit(a)}, ${sqlLit(b)})`).join(',\n    ');

lines.push(`
-- The TypeScript matrix and the SQL table must be identical, in both directions.
with ts (from_status, to_status) as (
  values
    ${tsPairs}
),
only_in_sql as (
  select t.from_status::text, t.to_status::text from order_transitions t
  except select from_status, to_status from ts
),
only_in_ts as (
  select from_status, to_status from ts
  except select t.from_status::text, t.to_status::text from order_transitions t
)
insert into test.parity (kind, label, passed, detail)
select 'transitions',
       'la matrice TypeScript et la table order_transitions sont identiques',
       not exists (select 1 from only_in_sql) and not exists (select 1 from only_in_ts),
       nullif(concat_ws(' | ',
         (select 'seulement en SQL : ' || string_agg(from_status || '->' || to_status, ', ') from only_in_sql),
         (select 'seulement en TS : '  || string_agg(from_status || '->' || to_status, ', ') from only_in_ts)), '');

insert into test.parity (kind, label, passed, detail)
select 'transitions', format('la matrice compte %s transitions des deux côtés', ${ALLOWED_TRANSITIONS.length}),
       (select count(*) from order_transitions) = ${ALLOWED_TRANSITIONS.length},
       format('SQL=%s TypeScript=%s', (select count(*) from order_transitions), ${ALLOWED_TRANSITIONS.length});
`);

// ---------------------------------------------------------------- report
lines.push(`
\\echo ''
\\echo '============ PARITÉ SQL <-> TYPESCRIPT ============'
select kind as "domaine", count(*) as "tests",
       count(*) filter (where passed) as "ok",
       count(*) filter (where not passed) as "échecs"
  from test.parity group by kind order by kind;

select kind as "domaine", label as "test", coalesce(detail,'') as "détail"
  from test.parity where not passed order by id;

do $report$
declare failed integer; total integer;
begin
  select count(*) filter (where not passed), count(*) into failed, total from test.parity;
  raise notice '% vérifications de parité, % réussies, % en échec', total, total - failed, failed;
  if failed > 0 then
    raise exception 'SQL et TypeScript divergent sur % point(s)', failed;
  end if;
end;
$report$;
`);

process.stdout.write(lines.join('\n'));
